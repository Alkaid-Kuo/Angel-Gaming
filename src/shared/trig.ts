function normDeg(deg: number): number {
  const d = deg % 360;
  return d < 0 ? d + 360 : d;
}

/** cos(deg) × 10000 */
export function icos(deg: number): number {
  return COS[normDeg(deg)];
}

/** sin(deg) × 10000 */
export function isin(deg: number): number {
  return SIN[normDeg(deg)];
}

/** 向量 (dx, dy) 的方位角（整數度，0～359）：取內積最大者，同分取較小角度 */
export function angleOf(dx: number, dy: number): number {
  if (dx === 0 && dy === 0) throw new Error("angleOf: 零向量");
  let best = 0;
  let bestDot = -Infinity;
  for (let d = 0; d < 360; d++) {
    const dot = dx * COS[d] + dy * SIN[d];
    if (dot > bestDot) {
      bestDot = dot;
      best = d;
    }
  }
  return best;
}
